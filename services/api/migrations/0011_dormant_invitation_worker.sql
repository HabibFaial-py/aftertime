CREATE FUNCTION public.aftertime_invitation_worker_candidates()
RETURNS TABLE (job_id uuid)
LANGUAGE sql VOLATILE SECURITY DEFINER SET search_path = '' AS $$
  SELECT o.id FROM public.invitation_delivery_outbox o
  WHERE o.status = 'pending' AND o.next_attempt_at <= pg_catalog.clock_timestamp()
    AND (o.lease_until IS NULL OR o.lease_until <= pg_catalog.clock_timestamp())
  ORDER BY o.next_attempt_at, o.id LIMIT 100
$$;

-- Candidate lookup is advisory. Locks and all eligibility checks are repeated
-- in capsule -> invitation -> job order. A lease token must be freshly and
-- securely generated by the trusted worker, not derived from a public ID.
CREATE FUNCTION public.aftertime_invitation_worker_transition(p_job_id uuid, p_token uuid, p_action text)
RETURNS TABLE (job_id uuid, lease_until timestamptz, capsule_id uuid, invitation_id uuid,
  intended_email text, key_id text, nonce bytea, kdf_salt bytea, ciphertext bytea, secret_digest bytea)
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = '' SET timezone = 'UTC' AS $$
DECLARE
  v_capsule_id uuid; v_invitation_id uuid;
  c public.direct_capsules%ROWTYPE; i public.direct_capsule_invitations%ROWTYPE;
  o public.invitation_delivery_outbox%ROWTYPE; v_now timestamptz; v_status text;
BEGIN
  IF p_job_id IS NULL OR p_token IS NULL OR p_action IS NULL
     OR p_action NOT IN ('lease','prepare','sent','retry','fail') THEN RETURN; END IF;
  SELECT x.invitation_id, y.capsule_id INTO v_invitation_id, v_capsule_id
  FROM public.invitation_delivery_outbox x JOIN public.direct_capsule_invitations y ON y.id=x.invitation_id
  WHERE x.id=p_job_id;
  IF NOT FOUND THEN RETURN; END IF;
  SELECT * INTO c FROM public.direct_capsules x WHERE x.id=v_capsule_id FOR UPDATE SKIP LOCKED;
  IF NOT FOUND THEN RETURN; END IF;
  SELECT * INTO i FROM public.direct_capsule_invitations x
    WHERE x.id=v_invitation_id AND x.capsule_id=v_capsule_id FOR UPDATE SKIP LOCKED;
  IF NOT FOUND THEN RETURN; END IF;
  SELECT * INTO o FROM public.invitation_delivery_outbox x
    WHERE x.id=p_job_id AND x.invitation_id=v_invitation_id FOR UPDATE SKIP LOCKED;
  IF NOT FOUND OR o.status <> 'pending' THEN RETURN; END IF;
  v_now := pg_catalog.clock_timestamp();
  IF p_action = 'lease' THEN
    IF o.next_attempt_at > v_now OR (o.lease_until IS NOT NULL AND o.lease_until > v_now) THEN RETURN; END IF;
  ELSIF o.lease_token IS DISTINCT FROM p_token OR o.lease_until IS NULL OR o.lease_until <= v_now THEN
    RETURN;
  END IF;

  -- Eligibility is checked after every lock wait using database wall time.
  IF c.cancelled_at IS NOT NULL OR c.deleted_at IS NOT NULL OR i.revoked_at IS NOT NULL
     OR i.claimed_at IS NOT NULL OR i.claimed_user_id IS NOT NULL OR i.claim_secret_digest IS NULL
     OR v_now < c.created_at OR v_now < i.created_at THEN
    v_status := 'cancelled';
  ELSIF v_now >= i.expires_at THEN
    v_status := 'expired';
  ELSIF p_action = 'lease' AND o.attempts >= 5 THEN
    v_status := 'failed';
  ELSIF p_action = 'sent' THEN
    v_status := 'sent';
  ELSIF p_action = 'fail' OR (p_action = 'retry' AND o.attempts >= 5) THEN
    v_status := 'failed';
  END IF;
  IF v_status IS NOT NULL THEN
    UPDATE public.invitation_delivery_outbox x SET status=v_status, ciphertext=NULL,
      next_attempt_at=NULL, finished_at=v_now, lease_token=NULL, lease_until=NULL WHERE x.id=p_job_id;
    RETURN;
  END IF;
  IF p_action = 'lease' THEN
    UPDATE public.invitation_delivery_outbox x SET lease_token=p_token,
      lease_until=v_now + interval '60 seconds', attempts=x.attempts+1 WHERE x.id=p_job_id;
    RETURN QUERY SELECT p_job_id, v_now + interval '60 seconds', NULL::uuid, NULL::uuid,
      NULL::text, NULL::text, NULL::bytea, NULL::bytea, NULL::bytea, NULL::bytea;
  ELSIF p_action = 'prepare' THEN
    RETURN QUERY SELECT o.id, o.lease_until, c.id, i.id, i.intended_email,
      o.key_id, o.nonce, o.kdf_salt, o.ciphertext, i.claim_secret_digest;
  ELSE -- retry: bounded backoff, fresh token required for the next lease.
    UPDATE public.invitation_delivery_outbox x SET lease_token=NULL, lease_until=NULL,
      next_attempt_at=v_now + pg_catalog.make_interval(secs => LEAST(300, 30 * (1 << (o.attempts - 1))))
    WHERE x.id=p_job_id;
  END IF;
EXCEPTION WHEN OTHERS THEN
  RAISE EXCEPTION USING ERRCODE='P0001', MESSAGE='Invitation worker unavailable';
END $$;

ALTER FUNCTION public.aftertime_invitation_worker_candidates() OWNER TO postgres;
ALTER FUNCTION public.aftertime_invitation_worker_transition(uuid,uuid,text) OWNER TO postgres;
REVOKE ALL ON FUNCTION public.aftertime_invitation_worker_candidates() FROM PUBLIC, anon, authenticated, service_role, aftertime_invitation_worker;
REVOKE ALL ON FUNCTION public.aftertime_invitation_worker_transition(uuid,uuid,text) FROM PUBLIC, anon, authenticated, service_role, aftertime_invitation_worker;
GRANT EXECUTE ON FUNCTION public.aftertime_invitation_worker_candidates() TO aftertime_invitation_worker;
GRANT EXECUTE ON FUNCTION public.aftertime_invitation_worker_transition(uuid,uuid,text) TO aftertime_invitation_worker;
COMMIT;
